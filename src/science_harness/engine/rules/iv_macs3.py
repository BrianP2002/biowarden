"""Rules for MACS3 (pack iv): paired-end format, effective genome size, --extsize, peaks.xls start.

Verified on MACS3 3.0.4 (bio-py), synthetic data (a 50 kb genome of two contigs, paired-end
fragments of 85 +- 8 bases, 55-70 fragments per binding site, `-q 0.01`; a 1 Mb single-end data set
of 140 sharp peaks where the fragment model can be built). Every call exits 0 and writes INFO lines
only; no line warns about the traps below.

macs3.paired_end_format (slot read_layout, CALL rule, tier T1, optional declaration `read_layout`).
GEN-26 (macs3-project/MACS#486). `-f BAM`, `-f SAM` and the default `-f AUTO` (log: "Detected
format is: BAM") read a paired-end BAM in single-end mode: "Paired-End mode is off", 1200 records
give `total tags in treatment: 600` (flags 99 and 83 are counted, flags 147 and 163 give 0 tags)
and every first mate is extended by `--extsize` (200 with `--nomodel`) instead of using the real
fragment. `-f BAMPE` writes `Paired-End mode is on`, `total fragments in treatment: 600` and uses
the fragment span (and ignores `--nomodel`, `--extsize` and `--shift`). Peak boundaries differ in
every data set (chr1 2799-3126 with BAM, 2812-3191 with BAMPE); with fragments of 85 bases and two
sites 250 bases apart BAMPE calls 8 peaks and `-f BAM --nomodel --extsize 200` or `147` calls 4.
`-f BAMPE` on a single-end BAM stops with a traceback (`Lambda must > 0`, exit 1): loud, so the
rule leaves it alone. The rule reads the treatment BAM header and the first records with the
standard library (aln_bam); a BAM whose mapped records are at least half paired (flag 0x1) is
paired. Fails: a single-end format on paired data (declared `single_end_tags` passes: the agent
means it); BAMPE with `single_end_tags` declared (contradiction); `fragments` declared with a
single-end format (contradiction). Not judged: BED, ELAND and other non-BAM formats, an unreadable
file, a BAM with fewer than half paired records.

macs3.effective_genome_size (slot genome_size, CALL rule, tier T1, no declaration). `-g` defaults
to `hs` = 2,913,022,398 (macs3 callpeak --help: "Default:hs"); the background lambda is
treatment (or control) tags * d / genome size, so a size that is not the genome's changes every
p- and q-value: on the 50 kb data with a control file `-g hs` gave fold enrichment 22.1 and
-log10(q) 72.8 for a peak that is 14.2 and 56.6 with `-g 30000` (same peak, same reads). The
effect needs a lambda that is not set by the local windows (small control windows below the
genome mean), which is common in real data. The rule sums the @SQ lengths of the treatment BAM
header and fails when the `-g` of the call (absent = hs; hs, mm, ce, dm or a number such as
1e9, 2.7e+9, 50000) is more than 5 times larger or smaller. A human-size BAM (3.1e9 against
hs 2.9e9) and mm (2.65e9 against 2.7e9) pass; BED-style formats and unreadable files are not
judged. The fix names the total: `-g <sum of @SQ>`.

macs3.extsize_needs_nomodel (slot fragment_length, CALL rule, tier T0, optional declaration
`fragment_length`). `--extsize N` is used only with `--nomodel`: on 140 sharp peaks (1 Mb),
`callpeak -f BAM -g 1000000 -q 0.01 --extsize 150` logs "predicted fragment length is 247 bps"
and writes the same 140 peaks, byte for byte in columns 1-3, as the run without `--extsize`;
`--nomodel --extsize 150` logs "Use 150 as fragment length" and calls peaks 1780-1966 where the
model run called 1843-2149. Exit 0, no warning. `--shift` is applied without `--nomodel`
(peaks 1787-2222), so only `--extsize` is judged. With `-f BAMPE` (or BEDPE, FRAG) `--extsize` is
ignored by design and the rule is silent. Declaration `fragment_length=model` passes (the agent
knows the model decides); `fixed` or nothing fails.

macs3.peaks_xls_start (slot index_base, FACT rule, tier T1, optional declaration
`peak_coordinates`). The `_peaks.xls` table starts with "# This file is generated by MACS" and its
`start` column is 1-based: narrowPeak `chr1 2853 3142` is xls `chr1 2854 3142 ... abs_summit 3006`,
summits.bed `chr1 3005 3006` (0-based). Fed to a BED consumer unchanged (bedtools, bedops, awk
printing `$1,$2,$3`, `cut -f1-3`) every peak starts one base late: a target that touches only the
first base of a peak is lost. Raw xls given straight to bedtools stops with "unable to open file"
(the comment header), so the silent route is a pipeline that strips the header first. The rule
applies to an existing file whose first line is the MACS header and fires when the command uses
the start column (awk `$2`, `cut -f1-3`, python `[1]`, a coordinate tool such as bedtools or
bedops) without showing a "- 1" on it; a command that names the narrowPeak or summits file of the
same run is left alone. `peak_coordinates=one_based` passes, `zero_based` fails.

macs3.control_contigs (slot completeness, CALL rule, tier T1, no declaration). MACS3 calls peaks
only on contigs that have reads in the control: a treatment contig without a single control read
is skipped without a word. Verified with the F72 data (8 peaks on chr1 and chr2) and a
background-only paired-end control: control with reads on both contigs 8 peaks (`-f BAMPE`) / 4
(`-f BAM --nomodel --extsize 200`), the same control cut to chr1 4 / 2 peaks, all on chr1; exit
0, stderr INFO lines only. With the single-end 180 kb data (four peaks on chr1, control reads on
chr2 and chr3 only) the run writes 0 peaks. The rule takes the mapped-read counts per contig
from the .bai index (standard library; the pseudo-bin 37450 holds n_mapped), or from the first
20,000 records when there is no index and the file ends before that, and fails when a contig with
at least 10 treatment reads has none in the control (all `-t` and `-c` files are summed).
Not judged: no `-c`, an unreadable file, a BAM that is longer than the sniff and has no index.
"""

from __future__ import annotations

import re
import struct
from dataclasses import dataclass, field
from pathlib import Path

from science_harness.engine.call import Call
from science_harness.engine.checks import CheckResult, Ctx, Match, checker, passed
from science_harness.engine.rules.aln_bam import Unreadable, read_alignment

SHORTCUTS = {"hs": 2_913_022_398, "mm": 2_652_783_500, "ce": 100_286_401, "dm": 142_573_017}
DEFAULT_GSIZE = "hs"
FACTOR = 5.0
SNIFF_RECORDS = 4000
ONE_BASED_HEADER = "# This file is generated by MACS"

SHORT = {
    "-t": "--treatment",
    "-c": "--control",
    "-f": "--format",
    "-g": "--gsize",
    "-s": "--tsize",
    "-n": "--name",
    "-q": "--qvalue",
    "-p": "--pvalue",
    "-m": "--mfold",
}
VALUED = frozenset(
    "--treatment --control --format --gsize --tsize --keep-dup --barcodes --max-count --outdir "
    "--name --verbose --shift --extsize --bw --d-min --mfold --qvalue --pvalue --scale-to --seed "
    "--tempdir --slocal --llocal --max-gap --min-length --broad-cutoff --fe-cutoff --ratio "
    "--buffer-size".split()
)
FLAGS = frozenset(
    "--bdg --SPMR --nomodel --fix-bimodal --down-sample --nolambda --broad --cutoff-analysis "
    "--call-summits --to-large --trackline --help".split()
)
MULTI = frozenset({"--treatment", "--control"})
PAIRED_FORMATS = frozenset({"BAMPE", "BEDPE", "FRAG"})
BAM_FORMATS = frozenset({"AUTO", "BAM", "SAM"})
LONG_NAMES = tuple(sorted(VALUED | FLAGS))


@dataclass
class CallPeak:
    values: dict[str, list[str]] = field(default_factory=dict)
    flags: set[str] = field(default_factory=set)

    def last(self, name: str) -> str | None:
        found = self.values.get(name)
        return found[-1] if found else None

    @property
    def fmt(self) -> str:
        return (self.last("--format") or "AUTO").upper()

    @property
    def treatment(self) -> list[str]:
        return self.values.get("--treatment", [])


def _long(name: str) -> str:
    """The option an argparse abbreviation stands for (`--ext` is `--extsize`)."""
    if name in LONG_NAMES:
        return name
    hits = [n for n in LONG_NAMES if n.startswith(name)]
    return hits[0] if len(hits) == 1 else name


def parse_callpeak(argv: tuple[str, ...] | list[str]) -> CallPeak:
    items = list(argv)
    i = items.index("callpeak") + 1 if "callpeak" in items else 0
    out = CallPeak()

    def take(name: str, first: str | None) -> None:
        nonlocal i
        got: list[str] = [] if first is None else [first]
        if first is None or name in MULTI:
            if name in MULTI:
                while i < len(items) and not items[i].startswith("-"):
                    got.append(items[i])
                    i += 1
            elif name == "--mfold":
                got = items[i : i + 2]
                i += 2
            elif i < len(items):
                got = [items[i]]
                i += 1
        out.values.setdefault(name, []).extend(got)

    while i < len(items):
        token = items[i]
        i += 1
        if token == "--":
            break
        if token.startswith("--"):
            name, eq, value = token.partition("=")
            name = _long(name)
            if name in VALUED:
                take(name, value if eq else None)
            else:
                out.flags.add(name)
        elif token.startswith("-") and len(token) > 1:
            name = SHORT.get(token[:2])
            if name is not None:
                attached = token[2:].lstrip("=") if len(token) > 2 else ""
                take(name, attached or None)
            else:
                out.flags.add(token)
    return out


# ---- the treatment file ------------------------------------------------------------------------


@dataclass(frozen=True)
class TreatmentInfo:
    path: Path
    mapped: int
    paired: int
    genome_bases: int  # sum of the @SQ lengths, 0 when the header has none

    @property
    def paired_share(self) -> float:
        return self.paired / self.mapped if self.mapped else 0.0


def read_treatment(ctx: Ctx, parsed: CallPeak) -> TreatmentInfo | None:
    """Header total and the paired share of the first treatment file; None when unreadable."""
    for name in parsed.treatment:
        path = ctx.resolve(name)
        if not path.is_file():
            continue
        try:
            aln = read_alignment(ctx, path, SNIFF_RECORDS)
        except (Unreadable, OSError, ValueError, EOFError):
            return None
        total = 0
        for line in aln.header:
            if line.startswith("@SQ"):
                match = re.search(r"\tLN:(\d+)", line)
                total += int(match.group(1)) if match else 0
        mapped = [r for r in aln.records if not r.flag & 0x4]
        return TreatmentInfo(path, len(mapped), sum(1 for r in mapped if r.flag & 0x1), total)
    return None


# ---- macs3.paired_end_format -------------------------------------------------------------------


@checker("iv_macs3_paired_format")
def iv_macs3_paired_format(call: Call, match: Match, ctx: Ctx) -> CheckResult:
    rule = match.rule
    assert rule.declare is not None
    key = rule.declare.key
    parsed = parse_callpeak(call.argv)
    fmt = parsed.fmt
    if fmt not in BAM_FORMATS | {"BAMPE"}:
        return passed()
    info = read_treatment(ctx, parsed)
    if info is None or info.mapped == 0:
        return passed()
    declared = call.declared.get(key)
    name = info.path.name
    if info.paired_share >= 0.5:
        if fmt == "BAMPE":
            if declared == "single_end_tags":
                return CheckResult(
                    "fail",
                    "declared_layout_contradicts_call",
                    f"you declared {key}=single_end_tags but -f BAMPE makes MACS3 use the "
                    f"fragments of the pairs in {name}, not single-end tags.",
                    expected="single_end_tags",
                    got="fragments",
                    fix=(f"use -f BAM for single-end tags, or declare {key}=fragments",),
                )
            return passed()
        if declared == "single_end_tags":
            return passed()
        shown = "-f " + fmt if "--format" in parsed.values else "no -f (AUTO)"
        message = (
            f"{name} is paired-end ({info.paired} of {info.mapped} "
            f"mapped records carry flag 0x1) but this call has {shown}: MACS3 reads it in "
            "single-end mode (log: 'Paired-End mode is off'), ignores the second mate of every "
            "pair and extends the first mate by --extsize instead of using the real fragment, so "
            "peak boundaries move and close sites merge."
        )
        if declared == "fragments":
            message = f"you declared {key}=fragments but " + message[0].lower() + message[1:]
        return CheckResult(
            "fail",
            "paired_end_read_as_single_end",
            message,
            expected="BAMPE",
            got=fmt,
            fix=(
                "use -f BAMPE (fragments; MACS3 then ignores --nomodel, --extsize and --shift)",
                f"or declare --declare {key}=single_end_tags if single-end tags are intended",
            ),
        )
    if info.paired_share > 0:
        if fmt != "BAMPE" and declared is None:
            return CheckResult(
                "unknown",
                "mixed_layout",
                f"{name} mixes paired ({info.paired}) and single-end records "
                f"({info.mapped - info.paired}); -f {fmt} reads the pairs as single-end tags.",
            )
        return passed()
    return passed()


# ---- macs3.effective_genome_size ---------------------------------------------------------------


def parse_gsize(text: str) -> int | None:
    value = text.strip().lower()
    if value in SHORTCUTS:
        return SHORTCUTS[value]
    try:
        return int(float(value.replace(",", "")))
    except ValueError:
        return None


@checker("iv_macs3_genome_size")
def iv_macs3_genome_size(call: Call, match: Match, ctx: Ctx) -> CheckResult:
    parsed = parse_callpeak(call.argv)
    if parsed.fmt not in BAM_FORMATS | {"BAMPE"}:
        return passed()
    given = parsed.last("--gsize")
    size = parse_gsize(given if given is not None else DEFAULT_GSIZE)
    info = read_treatment(ctx, parsed)
    if size is None or info is None or info.genome_bases <= 0 or size <= 0:
        return passed()
    ratio = size / info.genome_bases
    if 1 / FACTOR <= ratio <= FACTOR:
        return passed()
    shown = f"-g {given}" if given is not None else "no -g (the default is hs)"
    direction = "larger" if ratio > 1 else "smaller"
    factor = ratio if ratio > 1 else 1 / ratio
    return CheckResult(
        "fail",
        "genome_size_mismatch",
        f"{shown} means an effective genome size of {size:,} bases, {factor:,.0f} times "
        f"{direction} than the {info.genome_bases:,} bases in the header of {info.path.name}; "
        "MACS3 builds its background lambda from the genome size, so every p-value, q-value and "
        "fold enrichment is off and weak peaks are called (or true ones lost).",
        expected=info.genome_bases,
        got=size,
        fix=(
            f"use -g {info.genome_bases} (the total of the @SQ lengths, or the mappable "
            "genome size of the organism)",
        ),
    )


# ---- macs3.extsize_needs_nomodel ---------------------------------------------------------------


@checker("iv_macs3_extsize_nomodel")
def iv_macs3_extsize_nomodel(call: Call, match: Match, ctx: Ctx) -> CheckResult:
    rule = match.rule
    assert rule.declare is not None
    key = rule.declare.key
    parsed = parse_callpeak(call.argv)
    extsize = parsed.last("--extsize")
    if extsize is None or "--nomodel" in parsed.flags or parsed.fmt in PAIRED_FORMATS:
        return passed()
    declared = call.declared.get(key)
    if declared == "model":
        return passed()
    return CheckResult(
        "fail",
        "extsize_without_nomodel",
        f"--extsize {extsize} is used only together with --nomodel: without it MACS3 builds the "
        "fragment model and extends reads by the predicted fragment length (log: 'predicted "
        f"fragment length is N bps'), silently ignoring {extsize}.",
        expected="--nomodel",
        got=None,
        fix=(
            f"add --nomodel so that --extsize {extsize} is the fragment length",
            f"or drop --extsize and declare --declare {key}=model to use the predicted length",
        ),
    )


# ---- macs3.peaks_xls_start ---------------------------------------------------------------------

VIEWERS = frozenset(
    "head tail cat less more zless wc ls file stat du md5sum nl tac rev fold column grep egrep "
    "fgrep zgrep sed sort uniq tr xxd od hexdump cp mv rm ln diff cmp touch mkdir echo printf "
    "test find basename dirname".split()
)
COORDINATE_TOOLS = frozenset(
    "bedtools bedops bedmap sort-bed convert2bed liftOver computeMatrix samtools tabix bcftools "
    "multiBamSummary bedToBam".split()
)
SCRIPTING = re.compile(r"[gmn]?awk|python[\d.]*|python-\w+|perl[\d.]*|Rscript|R|ruby|julia")
SHELLS = frozenset("bash sh zsh dash ksh env xargs parallel timeout time nohup srun".split())
USES_START = re.compile(
    r"\$\{?2\}?(?!\d)|\$[A-Za-z_]*\[\s*1\s*\]|\b\w+\[\s*1\s*\]|\[\s*['\"]start['\"]\s*\]"
    r"|\.start\b|\bcut\b[^|;&]*-f\s*['\"]?(?:1-[23]|1,2|2)\b|usecols|read_csv|read_table"
    r"|read\.table|read\.delim|\bstart\b"
)
ADJUSTS = re.compile(
    r"\$\{?2\}?\s*-\s*1\b|\[\s*1\s*\]\)?\s*-\s*1\b|\bstart\w*\s*-\s*1\b|\.start\s*-\s*1\b"
    r"|\bstart\w*\s*=\s*\w+\s*-\s*1\b|(?i:\bone[_ -]?based\b|\b1[_ -]based\b)|-\s*1\s*\)?\s*,\s*\$3"
    r"|\.narrowPeak\b|summits\.bed\b"
)
XLS_NAME = re.compile(r"(?<![\w.+/@~-])[\w.+/@~-]*\.xls(?![\w-]|\.\w)")


def _is_macs_xls(ctx: Ctx, path: Path) -> bool:
    try:
        first = next(iter(ctx.lines(path, limit=1)), "")
    except (OSError, EOFError, UnicodeError):
        return False
    return first.startswith(ONE_BASED_HEADER)


def _uses_start(tool: str, text: str) -> bool:
    if tool in COORDINATE_TOOLS:
        return True
    if SCRIPTING.fullmatch(tool) or tool in SHELLS:
        if USES_START.search(text):
            return True
        return (
            re.search(r"\b(?:bedtools|bedops|bedmap|tabix|liftOver|computeMatrix)\b", text)
            is not None
        )
    return tool not in VIEWERS and re.search(r"\b(?:bedtools|bedops|bedmap)\b", text) is not None


@checker("iv_macs3_xls_start")
def iv_macs3_xls_start(call: Call, match: Match, ctx: Ctx) -> CheckResult:
    rule = match.rule
    assert rule.declare is not None
    key = rule.declare.key
    sheets = [p for p in match.files if _is_macs_xls(ctx, p)]
    if not sheets:
        return passed()
    text = XLS_NAME.sub(" ", "\n".join([call.tool, *call.argv, *call.context]))
    if not _uses_start(call.tool, text):
        return passed()
    declared = call.declared.get(key)
    name = sheets[0].name
    if declared == "one_based":
        return passed()
    if declared is None and ADJUSTS.search(text):
        return passed()
    if declared == "zero_based":
        message = (
            f"you declared {key}=zero_based but the start column of {name} (a MACS "
            "_peaks.xls) is 1-based: it is the narrowPeak start plus 1."
        )
    else:
        message = (
            f"the start column of {name} (a MACS _peaks.xls) is 1-based (narrowPeak start + 1), "
            "but this command uses it as it is, as a 0-based BED start: every peak starts one "
            "base late and a target touching only the first base is lost."
        )
    stem = name.removesuffix(".xls").removesuffix("_peaks")
    return CheckResult(
        "fail",
        "xls_start_is_one_based",
        message,
        expected="one_based",
        got=declared or "zero_based",
        fix=(
            f"use {stem}_peaks.narrowPeak (0-based BED) or subtract 1 from column 2 of the xls "
            "(awk 'BEGIN{OFS=\"\\t\"} {print $1,$2-1,$3}')",
            f"or declare --declare {key}=one_based if the command already handles it",
        ),
    )


# ---- macs3.control_contigs ---------------------------------------------------------------------

MIN_TREATMENT_READS = 10
BAI_PSEUDO_BIN = 37450
BAI_LIMIT = 32_000_000


def bai_mapped(data: bytes) -> list[int] | None:
    """Mapped reads per reference of a BAM index (pseudo-bin 37450, second chunk = n_mapped)."""
    try:
        if data[:4] != b"BAI\x01":
            return None
        (n_ref,) = struct.unpack_from("<i", data, 4)
        off, counts = 8, []
        for _ in range(n_ref):
            (n_bin,) = struct.unpack_from("<i", data, off)
            off += 4
            mapped = 0
            for _ in range(n_bin):
                bin_id, n_chunk = struct.unpack_from("<Ii", data, off)
                off += 8
                for i in range(n_chunk):
                    first, _second = struct.unpack_from("<QQ", data, off)
                    off += 16
                    if bin_id == BAI_PSEUDO_BIN and i == 1:
                        mapped = first
            (n_intv,) = struct.unpack_from("<i", data, off)
            off += 4 + 8 * n_intv
            counts.append(mapped)
        return counts
    except (struct.error, IndexError):
        return None


def contig_reads(ctx: Ctx, path: Path) -> dict[str, int] | None:
    """Mapped reads per contig of a BAM/SAM file; None when they cannot be counted here."""
    try:
        aln = read_alignment(ctx, path, SNIFF_RECORDS * 5)
    except (Unreadable, OSError, ValueError, EOFError):
        return None
    for index in (Path(f"{path}.bai"), path.with_suffix(".bai")):
        if index.is_file():
            counts = bai_mapped(ctx.read_bytes(index, BAI_LIMIT))
            if counts is not None and len(counts) == len(aln.refs):
                return dict(zip(aln.refs, counts, strict=True))
    if not aln.complete:
        return None
    seen: dict[str, int] = {}
    for rec in aln.records:
        if not rec.flag & 0x4 and rec.ref != "*":
            seen[rec.ref] = seen.get(rec.ref, 0) + 1
    return seen


def _sum_reads(ctx: Ctx, names: list[str]) -> dict[str, int] | None:
    total: dict[str, int] = {}
    for name in names:
        path = ctx.resolve(name)
        if not path.is_file():
            return None
        counts = contig_reads(ctx, path)
        if counts is None:
            return None
        for contig, n in counts.items():
            total[contig] = total.get(contig, 0) + n
    return total


@checker("iv_macs3_control_contigs")
def iv_macs3_control_contigs(call: Call, match: Match, ctx: Ctx) -> CheckResult:
    parsed = parse_callpeak(call.argv)
    controls = parsed.values.get("--control", [])
    if not controls or not parsed.treatment or parsed.fmt not in BAM_FORMATS | {"BAMPE"}:
        return passed()
    treated = _sum_reads(ctx, parsed.treatment)
    control = _sum_reads(ctx, controls)
    if treated is None or control is None:
        return passed()
    lost = {c: n for c, n in treated.items() if n >= MIN_TREATMENT_READS and control.get(c, 0) == 0}
    if not lost:
        return passed()
    shown = ", ".join(f"{c} ({n} treatment reads)" for c, n in list(lost.items())[:3])
    more = f" and {len(lost) - 3} more" if len(lost) > 3 else ""
    return CheckResult(
        "fail",
        "control_lacks_contigs",
        f"the control ({', '.join(controls)}) has no reads on {shown}{more}: MACS3 calls peaks "
        "only on contigs that have control reads, so every peak on them is dropped without a "
        "message (exit 0).",
        expected=sorted(lost),
        got=[],
        fix=(
            "use a control that covers the same contigs, or drop -c for this run",
            "or compare the contigs of both BAMs (samtools idxstats) before calling peaks",
        ),
    )
