"""Regenerate docs/families.md from the family modules (id, convention, locus, one-line error).

python tools/make_families_doc.py > docs/families.md
"""

from __future__ import annotations

import importlib
import inspect
import re
from collections import defaultdict

from biowarden.bench.tasks import families as core
from biowarden.bench.tasks.extra import _module_names
from biowarden.bench.tasks.locus import locus_of

DOMAINS = [  # (title, first id, last id)
    ("Original families", 1, 28),
    ("Read alignment", 29, 40),
    ("RNA-seq quantification", 41, 52),
    ("Variants and genotypes", 53, 64),
    ("Intervals, peaks, liftover, coverage tracks", 65, 76),
    ("Sequence processing, search and multiple alignment", 77, 88),
    ("Protein structure and protein-model plumbing", 89, 100),
    ("Single-cell and virtual-cell inputs", 101, 112),
]


def first_sentence(text: str) -> str:
    text = re.sub(r"\s+", " ", text.strip())
    text = re.sub(r"^F\d+ \w+(?: \([^)]*\))?:?\s*", "", text)
    match = re.match(r"(.{20,260}?[.;:])(\s|$)", text)
    return (match.group(1) if match else text[:200]).rstrip(":;")


def rows() -> dict[int, tuple[str, str, str, str]]:
    out: dict[int, tuple[str, str, str, str]] = {}
    for fid, fn in (
        ("F1", core.build_f1),
        ("F2", core.build_f2),
        ("F3", core.build_f3),
        ("F4", core.build_f4),
    ):
        doc = inspect.getdoc(fn) or ""
        slot, _, rest = doc.partition(":")
        out[int(fid[1:])] = (
            fid,
            slot.replace(" (must-detect)", ""),
            locus_of(fid),
            first_sentence(rest),
        )
    for name in _module_names():
        module = importlib.import_module(f"biowarden.bench.tasks.extra.{name}")
        spec = module.SPEC
        out[int(spec.id[1:])] = (
            spec.id,
            spec.slot,
            locus_of(spec.id),
            first_sentence(module.__doc__ or ""),
        )
    return out


def main() -> None:
    table = rows()
    print("# Task families\n")
    print(
        "Each family builds paired workspaces from a seed: the **clean** twin and the **faulted** "
        "twin\n"
        "share biology and task wording and differ only in the fact that triggers the trap; the "
        "truth is\n"
        "never in the workspace. *Locus* is the layer where the error lives (data, tool default, "
        "user\n"
        "statement, stale documentation, wrapper script). Generated by "
        "`tools/make_families_doc.py`.\n"
    )
    counts: dict[str, int] = defaultdict(int)
    for _, _, locus, _ in table.values():
        counts[locus] += 1
    print(
        "Families by locus: "
        + ", ".join(f"{k} {v}" for k, v in sorted(counts.items()))
        + f"; total {len(table)}.\n"
    )
    for title, low, high in DOMAINS:
        chosen = [table[i] for i in sorted(table) if low <= i <= high]
        if not chosen:
            continue
        print(f"## {title}\n")
        print("| ID | Convention | Locus | Error |\n|---|---|---|---|")
        for fid, slot, locus, text in chosen:
            print(f"| {fid} | {slot} | {locus.replace('_', ' ')} | {text.replace('|', '/')} |")
        print()


if __name__ == "__main__":
    main()
